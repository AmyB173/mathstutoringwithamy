        <p><em>Overview:</em></p>

        <ul>
          <li>Bright Year 7s often spend the <span class="key">first term repeating primary school work</span>, and lose their enthusiasm for maths.</li>
          <li><span class="key">Fluent algebra</span> is the tool that unlocks the hardest secondary maths, in the same way times tables unlock primary maths.</li>
          <li>Children who have it start using it <em>everywhere</em>: geometry, perimeter, area, sequences.</li>
          <li>That is why I am running a <span class="key">Year 7 Accelerator group from January</span>.</li>
        </ul>

        <h2>They were flying in primary school</h2>

        <p>They were <strong>great at maths in primary</strong>. They probably enjoyed all the challenge material the teacher gave them, and they were eagerly looking forward to the next step when they got to secondary school.</p>

        <p>Then, after the first few weeks, they slowly came to realise they were doing <em>primary school work on repeat</em>, especially in the first term. Perhaps the teacher is giving them lots of repetitive practice. Maybe they are being pushed to try some harder questions, but it is not much, and nothing particularly new.</p>

        <h2>What often happens next</h2>

        <p>Students <span class="key">lose their enthusiasm for the subject</span>. They notice that other subjects, perhaps ones they never studied in primary, are becoming more interesting. Maths turns into the place where they sit and practise things they already know, or things that are too easy for them.</p>

        <p>This is where we fail our bright Year 7 students. <strong>Year 7 is when they are most eager</strong>, and that energy is exactly what we should be using to give them a fantastic grounding.</p>

        <h2>Why algebra matters so much</h2>

        <p>In many other countries, algebra is introduced earlier and fluency is encouraged at a much younger age. In the same way that <em>times tables give children access to so many other topics at primary school</em>, <span class="key">fluent algebra gives them access to so many topics at GCSE</span>.</p>

        <p>What I often see is that even bright students in Year 9 and Year 10 do not have the algebraic fluency and confidence to use algebra to solve problems. There are often only one or two lessons in a whole year focused on forming and solving equations. This could be developed much more quickly, and students could be taught to apply it to a wide variety of situations.</p>

        <p>If we taught fluent algebra to students at a young age, we could bring it into <strong>nearly every geometry lesson</strong> too.</p>

        <h2>What this looks like in a Year 7 lesson</h2>

        <p>Take a question like this:</p>

        <div class="blog-worked">
          <p><em>In a triangle, the second angle is twice the first angle, and the third angle is 20&deg; more than the first angle. Find the largest angle.</em></p>
        </div>

        <p>A student without algebra fluency will often <strong>guess and check</strong>, or get stuck. A student who is fluent does this:</p>

        <ul>
          <li>Calls the first angle <span class="key">x</span>, and writes the other two as <span class="key">2x</span> and <span class="key">x + 20</span>.</li>
          <li>Writes <span class="key">x + 2x + x + 20 = 180</span>, because the angles in a triangle add up to 180&deg;.</li>
          <li>Simplifies it to <span class="key">4x + 20 = 180</span> and solves it: <span class="key">x = 40</span>.</li>
          <li>So the angles are 40&deg;, 80&deg; and 60&deg;, and <strong>the largest is 80&deg;</strong>.</li>
        </ul>

        <p>They are using the <em>same angle facts they learnt in primary</em>. The difference is that now they have a tool to use them with. Once they have it, they start reaching for it in perimeter, area and sequences questions too.</p>

        <h2>Just a caveat</h2>

        <p>Secondary maths teachers have a good reason for that first term repeating primary. Year 7 classes come from lots of different primary schools, and time is often spent making sure everyone has the same foundations. This is why schools, who have to make maths work for everyone, and tutoring are different. <em>Tutoring can be incredibly targeted.</em></p>

        <p>The benefit of seeing GCSE content early is that when it is taught again at school, your child will be able to <strong>really thrive</strong>, and the algebra they have learnt lets them go further with it. <span class="key">Times tables and number bonds unlock primary maths. Algebra unlocks the hardest secondary maths.</span></p>

